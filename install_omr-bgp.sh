#!/bin/sh
set -eu

# OpenMPTCProuter — BIRD 3 + omr_bgp module setup for Debian 13 (Trixie).
# No interactive prompts. Compatible with POSIX sh (dash, busybox sh, bash).
#
# Steps:
#   1. Installs bird3 from the Debian archive
#   2. Replaces /etc/bird/bird.conf with a minimal one when it is still the
#      package's own (a customised one is kept, the include line appended)
#   3. Creates /etc/bird/omr-bgp.conf root:bird 0640 (it holds the BGP
#      passwords) and starts BIRD
#   4. Deploys omr_bgp.py to /usr/share/omr-admin, restarts omr-admin
#
# The BGP neighbors, AS and pools are then set with the omr-admin API
# (docs/omr-bgp.md). Tunables from the environment, e.g.:
#   sudo BGP_ROUTER_ID=192.0.2.10 sh ./install_omr-bgp.sh
#   sudo OMR_BGP_FILE=./omr_bgp.py sh ./install_omr-bgp.sh   (local copy, no download)

# Commit (or branch) omr_bgp.py is downloaded from: match the installed omradmin.py
OMR_ADMIN_VERSION="${OMR_ADMIN_VERSION:-develop}"
# A local omr_bgp.py to install instead of downloading one
OMR_BGP_FILE="${OMR_BGP_FILE:-}"
# BIRD router id: the VPS's public IPv4 when empty
BGP_ROUTER_ID="${BGP_ROUTER_ID:-}"

BIRD_CONF="/etc/bird/bird.conf"
BIRD_INCLUDE="/etc/bird/omr-bgp.conf"
DEST="/usr/share/omr-admin/omr_bgp.py"

log()  { echo "[$(date '+%H:%M:%S')] $*"; }
die()  { echo "ERROR: $*" >&2; exit 1; }
step() { echo; echo "==> $*"; }

BGP_TMP=""
trap '[ -z "$BGP_TMP" ] || rm -f "$BGP_TMP"' EXIT
trap 'exit 1' HUP INT TERM

[ "$(id -u)" -eq 0 ] || die "Run as root (sudo $0)"
grep -q '^VERSION_ID="13"' /etc/os-release 2>/dev/null || log "WARNING: not Debian 13, continuing anyway"
[ -z "$OMR_BGP_FILE" ] || [ -f "$OMR_BGP_FILE" ] || die "OMR_BGP_FILE=${OMR_BGP_FILE} not found"

# ---------------------------------------------------------------------------
# 1. BIRD 3
# ---------------------------------------------------------------------------
step "Installing bird3..."
apt-get update -qq
# bird.conf is a conffile: rewritten below, a later upgrade must keep ours
# without asking on stdin
DEBIAN_FRONTEND=noninteractive apt-get install -y -qq \
    -o Dpkg::Options::=--force-confdef -o Dpkg::Options::=--force-confold bird3 curl ca-certificates

# ---------------------------------------------------------------------------
# 2. bird.conf
# ---------------------------------------------------------------------------
step "Configuring ${BIRD_CONF}..."
if [ -z "$BGP_ROUTER_ID" ]; then
    BGP_ROUTER_ID=$(ip -4 route get 1.1.1.1 2>/dev/null | sed -n 's/.* src \([0-9.]*\).*/\1/p')
fi
[ -n "$BGP_ROUTER_ID" ] || die "No public IPv4 found for the router id: set BGP_ROUTER_ID"

pkg_md5=$(dpkg-query -W -f='${Conffiles}\n' bird3 | awk -v f="$BIRD_CONF" '$1 == f {print $2}')
cur_md5=$(md5sum "$BIRD_CONF" 2>/dev/null | cut -d' ' -f1)
if [ ! -f "$BIRD_CONF" ] || [ "$cur_md5" = "$pkg_md5" ]; then
    # The package's sample exports every route to the kernel and runs
    # protocols omr-admin does not need: a minimal one instead
    cat > "$BIRD_CONF" <<EOF
# BIRD 3 for OpenMPTCProuter (install_omr-bgp.sh). The BGP protocols are
# generated by omr-admin in ${BIRD_INCLUDE}: configure them with its API.
log syslog all;
router id ${BGP_ROUTER_ID};

protocol device {
}

include "${BIRD_INCLUDE}";
EOF
    log "Minimal ${BIRD_CONF} written (router id ${BGP_ROUTER_ID})"
elif ! grep -qF "include \"${BIRD_INCLUDE}\";" "$BIRD_CONF"; then
    cp -p "$BIRD_CONF" "${BIRD_CONF}.bak-omr-bgp"
    printf '\ninclude "%s";\n' "$BIRD_INCLUDE" >> "$BIRD_CONF"
    log "Customised ${BIRD_CONF} kept (backup ${BIRD_CONF}.bak-omr-bgp), include line appended"
else
    log "Customised ${BIRD_CONF} kept, include line already there"
fi
chown root:bird "$BIRD_CONF"
chmod 640 "$BIRD_CONF"

# ---------------------------------------------------------------------------
# 3. Generated include, BIRD started
# ---------------------------------------------------------------------------
step "Preparing ${BIRD_INCLUDE}..."
# Empty static protocol until omr-admin writes the real one: a valid config
# BIRD can start with
[ -s "$BIRD_INCLUDE" ] || printf '# Generated by omr-admin (omr_bgp.py)\nprotocol static omr_routers {\n\tipv4;\n}\n' > "$BIRD_INCLUDE"
chown root:bird "$BIRD_INCLUDE"
chmod 640 "$BIRD_INCLUDE"

bird -p -c "$BIRD_CONF" || die "${BIRD_CONF} does not parse"
systemctl enable bird
systemctl restart bird
# bird -f: the unit is active before the control socket is there
_i=0
until birdc show status >/dev/null 2>&1; do
    _i=$((_i + 1))
    [ "$_i" -lt 15 ] || die "BIRD is not answering on its control socket (journalctl -u bird)"
    sleep 1
done
log "$(birdc show status | head -1 | sed 's/ ready\.//') running"

# ---------------------------------------------------------------------------
# 4. omr_bgp.py
# ---------------------------------------------------------------------------
step "Deploying omr_bgp.py..."
mkdir -p "$(dirname "$DEST")"
# Into a temp file next to it, checked, then renamed: never a truncated
# module (or an error page) in place of the live one
BGP_TMP=$(mktemp "${DEST}.XXXXXX")
if [ -n "$OMR_BGP_FILE" ]; then
    cp "$OMR_BGP_FILE" "$BGP_TMP"
else
    curl -fsSL "https://raw.githubusercontent.com/Ysurac/openmptcprouter-vps-admin/${OMR_ADMIN_VERSION}/omr_bgp.py" \
        -o "$BGP_TMP"
fi
python3 -c 'import sys; compile(open(sys.argv[1], "rb").read(), sys.argv[1], "exec")' "$BGP_TMP" \
    || die "omr_bgp.py does not compile; ${DEST} left unchanged"
chmod 644 "$BGP_TMP"
mv -f "$BGP_TMP" "$DEST"
BGP_TMP=""
log "  -> ${DEST}"

grep -q 'import omr_bgp' /usr/bin/omradmin.py 2>/dev/null \
    || log "WARNING: /usr/bin/omradmin.py does not load omr_bgp: update omr-vps-admin"
systemctl restart omr-admin 2>/dev/null || true
log "omr-admin restarted."

echo
echo "================================================================"
echo " OpenMPTCProuter — BIRD 3 + omr_bgp setup complete"
echo "================================================================"
echo "  BIRD config    : ${BIRD_CONF} (router id ${BGP_ROUTER_ID})"
echo "  Generated      : ${BIRD_INCLUDE}"
echo "  Module         : ${DEST}"
echo ""
echo "  Next, with an admin token of omr-admin:"
echo "    POST /bgp         AS, neighbors and pools"
echo "    POST /bgp/router  a public IP for each router (MQVPN fixed_ip needed)"
echo "    GET  /bgp         state; birdc show protocols for the sessions"
echo "  See docs/omr-bgp.md"
echo "================================================================"
